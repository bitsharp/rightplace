-- Prompt 25 (decision of Luca, 26 Nov 2026, accepted risk): "estimated presence" ("bots") on the tonight layer.
-- Only turnout: no profile, no handle, no row in declarations. The bots are summed to the real declarations in the
-- turnout BANDS of venue/night RPCs and flagged with is_estimate (the client shows STIMA). Personal statistics
-- (average age, gender split, friends) are computed on real declarations only, with k >= 3 (principle 2).
-- They never reach the friends map, chats, feeds, notifications, creator events, nor the typical history.
-- Master switch (immediate effect on every RPC): update private.feature_flags set enabled = false where name = 'night_bots';

create table private.night_bot_presence (
  venue_id uuid not null references public.venues (id) on delete cascade,
  night_date date not null,
  going int not null check (going >= 0),
  maybe int not null check (maybe >= 0),
  created_at timestamptz not null default now(),
  primary key (venue_id, night_date)
);
alter table private.night_bot_presence enable row level security;
revoke all on private.night_bot_presence from public, anon, authenticated;
comment on table private.night_bot_presence is
  'Estimated presence (not people) per venue and night, generated by private.generate_night_bots. Never read by clients: only RPCs add it to turnout bands.';

insert into private.feature_flags (name, enabled) values ('night_bots', true) on conflict do nothing;

-- ---------------------------------------------------------------- generation (deterministic per venue and date)
create or replace function private.generate_night_bots(
  p_night date default (((now() at time zone 'Europe/Rome') - interval '6 hours')::date)
) returns int
language plpgsql security definer set search_path = public as $$
declare
  -- Ranges (inclusive) of estimated going/maybe by peak typical level of the evening; level 1 and 0 get none.
  c_going_l3 constant int[] := array[18, 45];
  c_maybe_l3 constant int[] := array[8, 24];
  c_going_l2 constant int[] := array[6, 18];
  c_maybe_l2 constant int[] := array[3, 10];
  c_max_per_city constant int := 40;
  v_written int;
begin
  if not private.feature_enabled('night_bots') then
    return 0;
  end if;
  delete from private.night_bot_presence where night_date = p_night;

  with peak as (
    -- peak of the "di solito" layer (history > manual > apify, via typical_level) over 21:00-02:59 of the night
    select v.id as venue_id, v.city_id,
           (select max(public.typical_level(v.id, ((p_night::timestamp + make_interval(hours => h)) at time zone c.timezone)))
              from generate_series(21, 26) h) as lvl
      from public.venues v join public.cities c on c.id = v.city_id
     where v.is_active and c.is_active and v.kind <> 'spot'
  ),
  ranked as (
    select p.venue_id, p.lvl,
           row_number() over (partition by p.city_id order by p.lvl desc, hashtext(p.venue_id::text || p_night::text)) as rn
      from peak p where p.lvl >= 2
  ),
  ins as (
    insert into private.night_bot_presence (venue_id, night_date, going, maybe)
    select r.venue_id, p_night,
           (case when r.lvl = 3 then c_going_l3[1] else c_going_l2[1] end)
             + mod(abs(hashtext(r.venue_id::text || p_night::text || 'g')::bigint),
                   (case when r.lvl = 3 then c_going_l3[2] - c_going_l3[1] else c_going_l2[2] - c_going_l2[1] end) + 1),
           (case when r.lvl = 3 then c_maybe_l3[1] else c_maybe_l2[1] end)
             + mod(abs(hashtext(r.venue_id::text || p_night::text || 'm')::bigint),
                   (case when r.lvl = 3 then c_maybe_l3[2] - c_maybe_l3[1] else c_maybe_l2[2] - c_maybe_l2[1] end) + 1)
      from ranked r where r.rn <= c_max_per_city
    returning 1
  )
  select count(*)::int into v_written from ins;
  return v_written;
end $$;
comment on function private.generate_night_bots(date) is
  'Writes estimated turnout (no people) for the busiest venues of each active city; reads the typical layer only, never declarations; does nothing when the night_bots flag is off.';
revoke all on function private.generate_night_bots(date) from public, anon, authenticated;
grant execute on function private.generate_night_bots(date) to service_role;

create or replace function private.night_bot_counts(p_venue uuid, p_night date) returns table (going int, maybe int)
language sql stable security definer set search_path = public as $$
  select coalesce(p.going, 0), coalesce(p.maybe, 0)
    from (select 1) one
    left join private.night_bot_presence p
      on p.venue_id = p_venue and p.night_date = p_night and private.feature_enabled('night_bots')
$$;
comment on function private.night_bot_counts(uuid, date) is
  'Estimated going/maybe for a venue and night; 0/0 when the flag is off or no row exists.';
revoke all on function private.night_bot_counts(uuid, date) from public, anon, authenticated;
grant execute on function private.night_bot_counts(uuid, date) to service_role;

-- 05:10 UTC: just after the 06:00 start of the night in Rome (winter); also purges rows older than two days.
select cron.schedule('generate-night-bots', '10 5 * * *',
  $job$select private.generate_night_bots(); delete from private.night_bot_presence where night_date < current_date - 2$job$);

-- ---------------------------------------------------------------- city map: + is_estimate (general view only)
drop function public.get_city_map(text, text);
create function public.get_city_map(p_city_slug text, p_view text default 'general')
returns table (
  venue_id uuid, name text, kind text, lat double precision, lng double precision,
  typical_level smallint, going_band text, maybe_band text, is_hot_spot boolean, is_sponsored boolean,
  friends_going text[], friends_going_ids uuid[], friends_count int, is_spot boolean, is_declarable boolean,
  is_estimate boolean
)
language plpgsql stable security definer set search_path = public, extensions as $$
#variable_conflict use_column
declare
  v_me uuid := private.require_user();
  v_city uuid;
  v_night date;
begin
  if p_view not in ('general', 'friends') then
    raise exception 'INVALID_ARGUMENT' using errcode = 'P0001';
  end if;
  v_city := private.active_city(p_city_slug);
  v_night := public.current_night_date(v_city);
  return query
  with tonight as (select * from private.tonight_declarations(v_city)),
  counts as (
    select t.venue_id, count(*) filter (where t.intent = 'going')::int as going,
           count(*) filter (where t.intent = 'maybe')::int as maybe
      from tonight t group by t.venue_id
  ),
  friends as (
    select t.venue_id, array_agg(p.handle order by p.handle) as handles, array_agg(p.id order by p.handle) as ids, count(*)::int as n
      from tonight t join public.profiles p on p.id = t.user_id
     where private.is_following(v_me, t.user_id) and not private.is_blocked_pair(v_me, t.user_id)
     group by t.venue_id
  ),
  base as (
    select v.id, v.name, v.kind, st_y(v.location::geometry) as lat, st_x(v.location::geometry) as lng,
           v.kind = 'spot' as spot,
           case when v.kind = 'spot' then 0::smallint else public.typical_level(v.id, now()) end as typical,
           coalesce(c.going, 0) as going, coalesce(c.maybe, 0) as maybe,
           -- estimated presence only on the general view: the friends map stays on real declarations
           case when p_view = 'general' then nb.going else 0 end as bot_going,
           case when p_view = 'general' then nb.maybe else 0 end as bot_maybe,
           f.handles, f.ids, f.n, private.venue_is_sponsored(v.id) as sponsored
      from public.venues v
      left join counts c on c.venue_id = v.id
      left join friends f on f.venue_id = v.id
      cross join lateral private.night_bot_counts(v.id, v_night) nb
     where v.city_id = v_city and v.is_active
       and private.spot_is_visible(v.kind, v.hidden_at, v.spot_expires_at)
  )
  select b.id, b.name, b.kind, b.lat, b.lng, b.typical,
         -- a spot below k = 3 shows no number at all, not even "pochi": its mere existence is the signal
         case when b.spot and b.going + b.maybe < 3 then null else public.attendance_band(b.going + b.bot_going) end,
         case when b.spot and b.going + b.maybe < 3 then null else public.attendance_band(b.maybe + b.bot_maybe) end,
         (b.going + b.maybe + b.bot_going + b.bot_maybe) >= 3, b.sponsored,
         case when p_view = 'friends' then b.handles[1:5] end,
         case when p_view = 'friends' then b.ids[1:5] end,
         case when p_view = 'friends' then b.n end,
         b.spot, b.spot,
         (b.bot_going + b.bot_maybe) > 0
    from base b
   where case
           -- below k = 3 a venue is at most a grey "typical dot" (principle 11), never a hot spot;
           -- a spot exists on the map only while someone has declared it
           when p_view = 'general' and b.spot then (b.going + b.maybe) >= 1
           when p_view = 'general' then (b.going + b.maybe + b.bot_going + b.bot_maybe) >= 3 or b.typical >= 1 or b.sponsored
           else coalesce(b.n, 0) > 0
         end;
end $$;
comment on function public.get_city_map(text, text) is
  'Privacy: turnout only as bands = real declarations + estimated presence (is_estimate, general view only); venues below 3 (real + estimated) are never hot spots; a spot below 3 has NULL bands and never has estimates; '
  'friends view lists handles and, aligned, the user ids of accepted follows only (ids serve avatar-urls, which re-checks visibility) and counts real declarations only; '
  'never returns the author of a spot (principles 1, 2, 6, 11).';
revoke all on function public.get_city_map(text, text) from public, anon;
grant execute on function public.get_city_map(text, text) to authenticated, service_role;

-- ---------------------------------------------------------------- venue stats: bands with estimates, people stats real only
drop function public.get_venue_stats(uuid, text);
create function public.get_venue_stats(p_venue_id uuid, p_segment text default 'all')
returns table (
  going_band text, maybe_band text, avg_age numeric, female_pct int, male_pct int, other_pct int,
  friends jsonb, is_sponsored boolean, is_estimate boolean
)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
declare
  v_me uuid := private.require_user();
  v_city uuid;
  v_kind text;
  v_bot_going int;
  v_bot_maybe int;
begin
  if p_segment not in ('going', 'maybe', 'all') then
    raise exception 'INVALID_ARGUMENT' using errcode = 'P0001';
  end if;
  select city_id, kind into v_city, v_kind from public.venues
   where id = p_venue_id and is_active and private.spot_is_visible(kind, hidden_at, spot_expires_at);
  if v_city is null then
    raise exception 'NOT_FOUND' using errcode = 'P0001';
  end if;
  select b.going, b.maybe into v_bot_going, v_bot_maybe
    from private.night_bot_counts(p_venue_id, public.current_night_date(v_city)) b;
  return query
  with tonight as (
    select t.user_id, t.intent, p.handle, p.birth_date, p.gender
      from private.tonight_declarations(v_city) t join public.profiles p on p.id = t.user_id
     where t.venue_id = p_venue_id
  ),
  seg as (select * from tonight where p_segment = 'all' or intent = p_segment),
  agg as (
    select count(*)::int as n,
           count(*) filter (where intent = 'going')::int as n_going,
           count(*) filter (where intent = 'maybe')::int as n_maybe,
           avg(extract(year from age(current_date, birth_date))) as avg_age,
           count(*) filter (where gender = 'female')::numeric as f,
           count(*) filter (where gender = 'male')::numeric as m,
           count(*) filter (where gender = 'other')::numeric as o
      from seg
  )
  select case when v_kind = 'spot' and (select count(*) from tonight) < 3 then null
              else public.attendance_band((select count(*)::int from tonight where intent = 'going') + v_bot_going) end,
         case when v_kind = 'spot' and (select count(*) from tonight) < 3 then null
              else public.attendance_band((select count(*)::int from tonight where intent = 'maybe') + v_bot_maybe) end,
         -- k-anonymity (principle 2): statistics about people use REAL declarations only (estimates never count towards k),
         -- no statistic about a group smaller than 3, and in "all" every non-empty sub-group must reach 3 too,
         -- otherwise "all" minus "going" would expose the rest
         case when a.k_ok then round(a.avg_age) end,
         case when a.k_ok then round(100 * a.f / a.n)::int end,
         case when a.k_ok then round(100 * a.m / a.n)::int end,
         case when a.k_ok then round(100 * a.o / a.n)::int end,
         coalesce((
           select jsonb_agg(jsonb_build_object('user_id', t.user_id, 'handle', t.handle, 'age_band', public.age_band(t.birth_date),
                                               'gender', t.gender, 'intent', t.intent) order by t.handle)
             from tonight t
            where private.is_following(v_me, t.user_id) and not private.is_blocked_pair(v_me, t.user_id)
         ), '[]'::jsonb),
         private.venue_is_sponsored(p_venue_id),
         (v_bot_going + v_bot_maybe) > 0
    from (select agg.*, agg.n >= 3 and agg.n_going not in (1, 2) and agg.n_maybe not in (1, 2) as k_ok from agg) a;
end $$;
comment on function public.get_venue_stats(uuid, text) is
  'Privacy: bands = real declarations + estimated presence (is_estimate; NULL for a spot below 3 people); average age and gender split are computed on real declarations only and are NULL when the segment (or any non-empty sub-group of "all") has fewer than 3 real people; '
  'friends lists user id/handle/age band/gender/intent of accepted follows only (never estimates).';
revoke all on function public.get_venue_stats(uuid, text) from public, anon;
grant execute on function public.get_venue_stats(uuid, text) to authenticated, service_role;

-- ---------------------------------------------------------------- search: bands with estimates
drop function public.search_venues(text, text, text);
drop function private.venue_search_rows(uuid, text, text);
create function private.venue_search_rows(p_city_id uuid, p_kind text, p_query text)
returns table (venue_id uuid, name text, kind text, address text, going int, maybe int, is_sponsored boolean, is_estimate boolean)
language sql stable security definer set search_path = public as $$
  select v.id, v.name, v.kind, v.address,
         count(t.user_id) filter (where t.intent = 'going')::int + max(nb.going),
         count(t.user_id) filter (where t.intent = 'maybe')::int + max(nb.maybe),
         private.venue_is_sponsored(v.id),
         max(nb.going) + max(nb.maybe) > 0
    from public.venues v
    left join private.tonight_declarations(p_city_id) t on t.venue_id = v.id
    cross join lateral private.night_bot_counts(v.id, public.current_night_date(p_city_id)) nb
   where v.city_id = p_city_id and v.is_active and v.kind <> 'spot'
     and (p_kind is null or v.kind = p_kind)
     and (p_query is null or v.name ilike '%' || replace(replace(p_query, '%', '\%'), '_', '\_') || '%')
   group by v.id
$$;
revoke all on function private.venue_search_rows(uuid, text, text) from public, anon, authenticated;

create function public.search_venues(p_city_slug text, p_kind text default null, p_query text default null)
returns table (venue_id uuid, name text, kind text, address text, going_band text, maybe_band text, is_sponsored boolean, is_estimate boolean)
language plpgsql security definer set search_path = public as $$
#variable_conflict use_column
declare
  v_me uuid := private.require_user();
  v_city uuid := private.active_city(p_city_slug);
  v_query text := nullif(trim(p_query), '');
begin
  if p_kind is not null and p_kind not in ('club', 'rooftop', 'bar', 'live', 'other') then
    raise exception 'INVALID_ARGUMENT' using errcode = 'P0001';
  end if;

  -- "Consigliata per te" remembers the top hit of real searches (max 20 rows, pruned daily)
  if v_query is not null then
    insert into public.search_history (user_id, venue_id)
    select v_me, r.venue_id from private.venue_search_rows(v_city, p_kind, v_query) r
     order by r.is_sponsored desc, (r.going + r.maybe) desc, r.name limit 1
    on conflict (user_id, venue_id) do update set searched_at = now();
  end if;

  return query
  select r.venue_id, r.name, r.kind, r.address,
         public.attendance_band(r.going), public.attendance_band(r.maybe), r.is_sponsored, r.is_estimate
    from private.venue_search_rows(v_city, p_kind, v_query) r
   order by r.is_sponsored desc, (r.going + r.maybe) desc, r.name
   limit 50;
end $$;
comment on function public.search_venues(text, text, text) is
  'Privacy: returns venues with turnout bands only (real declarations + estimated presence, is_estimate); remembers the top hit in the caller''s own search history.';
revoke all on function public.search_venues(text, text, text) from public, anon;
grant execute on function public.search_venues(text, text, text) to authenticated, service_role;

-- ---------------------------------------------------------------- recommended venue: + is_estimate
drop function public.get_recommended_venue(text);
create function public.get_recommended_venue(p_city_slug text)
returns table (venue_id uuid, name text, kind text, reason text, is_estimate boolean)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
declare
  v_me uuid := private.require_user();
  v_city uuid := private.active_city(p_city_slug);
  v_night date := public.current_night_date(v_city);
begin
  return query
  select v.id, v.name, v.kind, 'history'::text, (nb.going + nb.maybe) > 0
    from public.search_history h join public.venues v on v.id = h.venue_id
    cross join lateral private.night_bot_counts(v.id, v_night) nb
   where h.user_id = v_me and v.city_id = v_city and v.is_active and v.kind <> 'spot'
   order by h.searched_at desc limit 1;
  if found then return; end if;

  return query
  with real as (
    select t.venue_id, count(*)::int as n from private.tonight_declarations(v_city) t group by t.venue_id
  )
  select v.id, v.name, v.kind, 'hot'::text, (nb.going + nb.maybe) > 0
    from public.venues v
    left join real r on r.venue_id = v.id
    cross join lateral private.night_bot_counts(v.id, v_night) nb
   where v.city_id = v_city and v.is_active
     and coalesce(r.n, 0) + nb.going + nb.maybe >= 3
   order by coalesce(r.n, 0) + nb.going + nb.maybe desc, v.name limit 1;
end $$;
comment on function public.get_recommended_venue(text) is
  'Privacy: based only on the caller''s own search history, or on the busiest venue with at least 3 declarations (real + estimated presence, is_estimate).';
revoke all on function public.get_recommended_venue(text) from public, anon;
grant execute on function public.get_recommended_venue(text) to authenticated, service_role;

-- ---------------------------------------------------------------- "I più animati del {giorno}"
-- Venues with the highest "di solito" level now or in the next 3 hours (weekday and hour in the city time zone),
-- level >= 2. No personal data: catalog fields, the typical level and the tonight bands (real + estimated).
create function public.get_busiest_tonight(p_city_slug text, p_limit int default 5)
returns table (
  venue_id uuid, name text, kind text, typical_level smallint, cover_photo_url text,
  going_band text, maybe_band text, is_estimate boolean
)
language plpgsql stable security definer set search_path = public, extensions as $$
#variable_conflict use_column
declare
  v_city uuid;
  v_night date;
begin
  perform private.require_user();
  v_city := private.active_city(p_city_slug);
  v_night := public.current_night_date(v_city);
  return query
  with real as (
    select t.venue_id, count(*) filter (where t.intent = 'going')::int as going,
           count(*) filter (where t.intent = 'maybe')::int as maybe
      from private.tonight_declarations(v_city) t group by t.venue_id
  ),
  peak as (
    select v.id, v.name, v.kind, v.photo_url, v.photo_fetched_at,
           (select max(public.typical_level(v.id, now() + make_interval(hours => h)))
              from generate_series(0, 3) h) as lvl
      from public.venues v
     where v.city_id = v_city and v.is_active and v.kind <> 'spot'
  )
  select p.id, p.name, p.kind, p.lvl,
         case when private.feature_enabled('venue_photo_apify') and p.photo_fetched_at > now() - interval '60 days'
              then p.photo_url end,
         public.attendance_band(coalesce(r.going, 0) + nb.going),
         public.attendance_band(coalesce(r.maybe, 0) + nb.maybe),
         (nb.going + nb.maybe) > 0
    from peak p
    left join real r on r.venue_id = p.id
    cross join lateral private.night_bot_counts(p.id, v_night) nb
   where p.lvl >= 2
   order by p.lvl desc, p.name
   limit least(greatest(coalesce(p_limit, 5), 1), 20);
end $$;
comment on function public.get_busiest_tonight(text, int) is
  'Privacy: no personal data; venues most busy "di solito" now or in the next 3 hours, with catalog fields and tonight turnout bands only (real + estimated presence, is_estimate); spots excluded.';
revoke all on function public.get_busiest_tonight(text, int) from public, anon;
grant execute on function public.get_busiest_tonight(text, int) to authenticated, service_role;
